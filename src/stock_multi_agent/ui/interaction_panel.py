"""User-initiated navigation and research follow-ups; never executes a trade."""
from __future__ import annotations

from hashlib import sha256
from inspect import signature
from math import ceil

import streamlit as st

from stock_multi_agent.models.chat import AssistantResponse
from stock_multi_agent.services.interaction_actions import build_interaction_actions


def _key(value: object) -> str:
    return sha256(str(value).encode('utf-8')).hexdigest()[:16]


def _kind(action) -> str:
    return str(getattr(action.kind, 'value', action.kind))


def _queue_prompt(prompt: str) -> None:
    st.session_state['pending_prompt'] = prompt


def _link_button(label: str, url: str, *, key: str, **kwargs):
    # Streamlit 1.40 did not expose link_button keys; normal widget keys stay stable.
    if 'key' in signature(st.link_button).parameters:
        kwargs['key'] = key
    return st.link_button(label, url, **kwargs)


def _render_browser_status(response: AssistantResponse, render_key: str) -> None:
    result = response.metadata.get('browser_actions', {})
    if not isinstance(result, dict):
        return
    status = result.get('status')
    if status == 'CONFIRMATION_REQUIRED':
        st.info('Bạn có muốn mở các trang liên quan trên trình duyệt máy này không? Chưa có trang nào được mở.')
        first, second = st.columns(2)
        if first.button('Đồng ý mở trang', key=f'confirm-open-{_key(render_key)}'):
            from stock_multi_agent.services.browser_automation import open_response_actions
            context = getattr(st, 'context', None)
            host = context.headers.get('Host') if context is not None else None
            response.metadata['browser_actions'] = open_response_actions(response, result.get('request_text', ''),
                state=st.session_state, host=host, execution_mode=st.session_state.get('interaction_execution_mode', 'STANDARD'),
                confirmed=True, enabled=False, max_tabs=st.session_state.get('interaction_max_tabs', 3),
                broker_url_template=st.session_state.get('interaction_broker_template') or None,
                broker_name=st.session_state.get('interaction_broker_name') or 'VNDIRECT')
            st.rerun()
        if second.button('Không mở', key=f'cancel-open-{_key(render_key)}'):
            response.metadata['browser_actions'] = {'status': 'CANCELLED', 'opened': [], 'skipped': []}
            st.rerun()
        return
    if status in {'OPENED', 'PARTIAL'}:
        st.caption('Đã yêu cầu trình duyệt mở trang.' if status == 'OPENED' else 'Đã mở một phần liên kết; các liên kết còn lại có thể mở thủ công bên dưới.')
        for opened in result.get('opened', []):
            label = opened.get('label') if isinstance(opened, dict) else str(opened)
            if label:
                st.caption('Đã mở: ' + label)
    elif status == 'NOT_LOCALHOST':
        st.caption('Tự mở trình duyệt chỉ hoạt động khi truy cập ứng dụng trên localhost. Bạn vẫn có thể dùng liên kết thủ công.')
    elif status == 'BROWSER_UNAVAILABLE':
        st.caption('Không mở được trình duyệt trên máy này. Bạn có thể dùng các liên kết thủ công bên dưới.')
    elif status == 'NO_SAFE_ACTIONS':
        st.caption('Chưa có liên kết phù hợp đủ an toàn để tự mở; báo cáo thiếu nguồn hoặc chưa xác minh sẽ không được thay bằng URL đoán.')
    elif status in {'OFFLINE', 'OFFLINE_BLOCKED'}:
        st.caption('OFFLINE: đã chặn thao tác mở trang ra ngoài.')
    elif status == 'CANCELLED':
        st.caption('Bạn đã chọn không mở trang cho phản hồi này.')


def render_interaction_actions(response: AssistantResponse, render_key: str) -> None:
    """Render links from validated deterministic actions, not URLs generated by LLMs."""
    profile = response.metadata.get('execution_profile', {})
    offline = (st.session_state.get('interaction_execution_mode') == 'OFFLINE'
               or profile.get('mode') == 'OFFLINE' or profile.get('external_allowed') is False)
    if offline:
        st.caption('OFFLINE: không hiển thị liên kết ra ngoài; dữ liệu phản hồi vẫn được giữ nguyên.')
        return
    _render_browser_status(response, render_key)
    try:
        actions = build_interaction_actions(
            response,
            broker_url_template=st.session_state.get('interaction_broker_template') or st.session_state.get('interaction_broker_url_template') or None,
            broker_name=st.session_state.get('interaction_broker_name') or 'Cổng giao dịch',
        )
    except ValueError:
        st.warning('Cấu hình liên kết không hợp lệ. Hãy kiểm tra địa chỉ HTTPS và mẫu mã cổ phiếu.')
        return
    if not actions:
        return
    base = 'interact-' + _key(render_key)
    with st.expander('Mở nhanh cổ phiếu, bảng giá và tài liệu', expanded=True):
        if st.session_state.get('interaction_auto_open', False):
            st.caption('Chế độ local tự mở trang phù hợp sau yêu cầu của bạn; các nút dưới đây để mở lại hoặc chọn trang khác. Ứng dụng không đặt lệnh.')
        else:
            st.caption('Tự mở trang đang tắt; dùng các nút bên dưới khi cần. Ứng dụng không đặt lệnh.')
        st.caption('Giá trên website có thể khác thời điểm dữ liệu phân tích; hãy kiểm tra mã và thời điểm cập nhật tại nguồn.')
        tickers = list(dict.fromkeys(action.ticker for action in actions if action.ticker))
        selected = None
        if tickers:
            selected = st.selectbox('Chọn mã để thao tác', tickers, key=f'{base}-ticker')
        selected_actions = [action for action in actions if action.ticker == selected]
        scope = f'{base}-{_key(selected)}'
        if selected:
            for column, (label, prompt) in zip(st.columns(3), [
                ('Phân tích mã', f'Phân tích {selected}'),
                ('Biểu đồ mã', f'Cho tôi biểu đồ {selected}'),
                ('Tìm báo cáo mã', f'Tìm báo cáo tài chính mới nhất của {selected}'),
            ]):
                column.button(label, key=f'{scope}-followup-{_key(label)}',
                              on_click=_queue_prompt, args=(prompt,), use_container_width=True)
        navigation = [action for action in selected_actions if _kind(action) not in {'REPORT', 'SOURCE', 'BROKER'}]
        columns = st.columns(3)
        for index, action in enumerate(navigation):
            with columns[index % 3]:
                _link_button(action.label, action.url, key=f'{scope}-link-{_key(action.id)}',
                             help=action.description, use_container_width=True)
        documents = [action for action in selected_actions if _kind(action) in {'REPORT', 'SOURCE'}]
        if selected:
            # Unscoped source links never silently become evidence for the selected stock.
            general = [action for action in actions if not action.ticker and _kind(action) in {'REPORT', 'SOURCE'}]
            if general:
                st.caption('Nguồn chưa gắn mã không được hiển thị như báo cáo của mã đang chọn; xem trích dẫn gốc trong phản hồi.')
        if documents:
            st.markdown('**Tài liệu và nguồn của mã đang chọn**' if selected else '**Tài liệu và nguồn**')
            pages = ceil(len(documents) / 8)
            page = int(st.number_input('Trang tài liệu', min_value=1, max_value=pages, value=1,
                                       step=1, key=f'{scope}-documents-page')) if pages > 1 else 1
            for action in documents[(page - 1) * 8:page * 8]:
                _link_button(action.label, action.url, key=f'{scope}-document-{_key(action.id)}')
                st.caption(f'URL nguồn: {action.url}')
                st.caption(f'Công bố: {action.published_at or "chưa xác định"} · Dữ liệu đến kỳ: {action.period_label or "chưa xác định"}')
                if action.description:
                    st.caption(action.description)
            st.caption(f'Hiển thị trang {page}/{pages} · {len(documents)} liên kết. Ngày đăng không thay thế kỳ dữ liệu; xem cảnh báo độ cũ/xác minh trong phản hồi.')
        elif selected:
            st.caption(f'Chưa có báo cáo gắn rõ với {selected} trong phản hồi này. Bấm “Tìm báo cáo mã” để yêu cầu tìm kiếm.')
        brokers = [action for action in actions if _kind(action) == 'BROKER' and action.ticker in (None, selected)]
        for action in brokers:
            st.caption('Chỉ điều hướng tới website bên ngoài. Bạn tự đăng nhập, kiểm tra đúng mã/giá và quyết định thao tác tại đó.')
            confirmation = f'Tôi muốn mở website giao dịch cho {selected}' if action.ticker else f'Tôi muốn mở cổng giao dịch (cần tự chọn mã {selected or "cổ phiếu"})'
            confirmed = st.checkbox(confirmation,
                                    value=False, key=f'{scope}-broker-confirm-{_key(action.id)}')
            _link_button(action.label, action.url, disabled=not confirmed,
                           key=f'{scope}-broker-{_key(action.id)}', help=action.description)
